"""Check that audio-extracted features fall in plausible ranges (M3).

The UCI dataset ships features only, not the audio they were computed from, so
we cannot run our Praat extraction on the original recordings and compare value
by value. What we can check:

1. Range check: features extracted from the sample WAVs, placed against the
   dataset's distribution (percentile, and whether they fall in the 1st-99th
   percentile band).
2. Sensitivity check: synthetic vowels with known, increasing jitter, shimmer
   and noise should give increasing measured jitter and shimmer, and falling HNR.

Usage (from the repo root):
    python -m research.feature_validation
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import numpy as np

from app.audio.features import REPRODUCIBLE_FEATURES, extract_features
from app.audio.load import TARGET_SR, Audio, load_audio
from app.audio.validate import validate_audio
from data.download import DEFAULT_DEST
from data.make_samples import SAMPLES_DIR, VoiceSpec, synth_vowel
from research.dataset import Dataset, load_dataset

RESULTS_DIR = Path(__file__).resolve().parent / "results"
LOW_PCT, HIGH_PCT = 1, 99

# Each sweep varies one synthesis parameter and reads one measured feature.
SWEEPS: dict[str, tuple[str, str, list[float]]] = {
    "jitter": ("jitter", "MDVP:Jitter(%)", [0.002, 0.004, 0.008, 0.012]),
    "shimmer": ("shimmer", "MDVP:Shimmer", [0.01, 0.03, 0.06, 0.09]),
    "noise": ("noise", "HNR", [0.001, 0.005, 0.02, 0.05]),
}


def range_check(features: dict[str, float], ds: Dataset) -> list[dict[str, Any]]:
    """Place each feature against the dataset (overall percentile, per-class medians)."""
    rows = []
    for name in REPRODUCIBLE_FEATURES:
        col = ds.X[name]
        value = features[name]
        lo, hi = np.percentile(col, [LOW_PCT, HIGH_PCT])
        rows.append(
            {
                "feature": name,
                "value": value,
                "percentile": float((col < value).mean() * 100),
                "median_parkinsons": float(col[ds.y == 1].median()),
                "median_healthy": float(col[ds.y == 0].median()),
                "in_range": bool(lo <= value <= hi),
            }
        )
    return rows


def sensitivity_sweeps() -> dict[str, list[dict[str, float]]]:
    """Measure one feature while increasing one synthesis parameter."""
    results = {}
    for sweep, (param, feature, values) in SWEEPS.items():
        rows = []
        for v in values:
            audio = Audio(synth_vowel(VoiceSpec(**{param: v})), TARGET_SR)
            rows.append({"input": v, "measured": extract_features(audio)[feature]})
        results[sweep] = rows
    return results


def run(ds: Dataset, samples_dir: Path = SAMPLES_DIR) -> dict[str, Any]:
    """Run both checks on every WAV in `samples_dir`."""
    samples = {}
    for path in sorted(samples_dir.glob("*.wav")):
        audio = load_audio(path.read_bytes())
        validate_audio(audio)
        samples[path.stem] = range_check(extract_features(audio), ds)
    return {"samples": samples, "sweeps": sensitivity_sweeps()}


def _monotonic(values: list[float], increasing: bool) -> bool:
    pairs = zip(values, values[1:], strict=False)
    return all((b > a) if increasing else (b < a) for a, b in pairs)


def to_markdown(results: dict[str, Any]) -> str:
    """Render the validation report."""
    parts = [
        "# Feature extraction validation",
        "",
        "_Generated by `research/feature_validation.py` — do not edit by hand._",
        "",
        "The UCI dataset contains features only, not audio, so our Praat extraction cannot be compared "
        "value-by-value with the published numbers. These checks show the extracted values are "
        "*plausible*, not that they equal what MDVP would have measured on the same recording.",
        "",
        "## 1. Range check on the sample recordings",
        "",
        f"Percentile = share of the 195 dataset recordings below the value. "
        f"Flagged ⚠ if outside the {LOW_PCT}st–{HIGH_PCT}th percentile band. "
        "The samples are **synthetic** (see `data/make_samples.py`).",
    ]
    for name, rows in results["samples"].items():
        flagged = [r["feature"] for r in rows if not r["in_range"]]
        parts += [
            "",
            f"### `{name}.wav`",
            "",
            f"{len(rows) - len(flagged)} of {len(rows)} features within range"
            + (f"; outside: {', '.join(f'`{f}`' for f in flagged)}." if flagged else "."),
            "",
            "| Feature | Value | Percentile | Median, Parkinson's | Median, healthy | In range |",
            "|---|---|---|---|---|---|",
        ]
        parts += [
            f"| `{r['feature']}` | {r['value']:.5g} | {r['percentile']:.0f} | "
            f"{r['median_parkinsons']:.5g} | {r['median_healthy']:.5g} | "
            f"{'✓' if r['in_range'] else '⚠'} |"
            for r in rows
        ]

    parts += [
        "",
        "## 2. Sensitivity check on synthetic vowels",
        "",
        "Each row is a synthetic vowel (150 Hz) with one parameter raised; the others stay at their defaults.",
    ]
    for sweep, (param, feature, _) in SWEEPS.items():
        rows = results["sweeps"][sweep]
        measured = [r["measured"] for r in rows]
        increasing = feature != "HNR"
        ok = _monotonic(measured, increasing)
        parts += [
            "",
            f"**{param} → `{feature}`**: {'moves in the expected direction ✓' if ok else 'NOT monotonic ⚠'}",
            "",
            f"| Synthesised {param} | Measured `{feature}` |",
            "|---|---|",
        ]
        parts += [f"| {r['input']:g} | {r['measured']:.5g} |" for r in rows]
    return "\n".join(parts) + "\n"


def main(argv: list[str] | None = None) -> int:
    """CLI entry point: write JSON and Markdown results."""
    parser = argparse.ArgumentParser(description="Validate audio feature extraction.")
    parser.add_argument("--data", type=Path, default=DEFAULT_DEST)
    parser.add_argument("--samples-dir", type=Path, default=SAMPLES_DIR)
    parser.add_argument("--out-dir", type=Path, default=RESULTS_DIR)
    args = parser.parse_args(argv)

    results = run(load_dataset(args.data), args.samples_dir)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "feature_validation.json").write_text(json.dumps(results, indent=1) + "\n")
    (args.out_dir / "feature_validation.md").write_text(to_markdown(results))
    print(f"Wrote {args.out_dir / 'feature_validation.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
